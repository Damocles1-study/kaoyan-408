# 选59(2025)：0,1,2 已在内存，m=3
def lru_pre(ref,m,pre):
    fr=list(pre); rec=list(pre); faults=0
    for p in ref:
        if p in fr: rec.remove(p); rec.append(p); continue
        faults+=1
        if len(fr)<m: fr.append(p); rec.append(p)
        else:
            v=rec.pop(0); fr[fr.index(v)]=p; rec.append(p)
    return faults
