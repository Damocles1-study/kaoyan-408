# -*- coding: utf-8 -*-
"""OS ch4 文件管理 —— 读书阶段 Python 独立复算"""
import math
K, M, G, T = 1024, 1024**2, 1024**3, 1024**4
ok = fail = 0
def chk(name, got, want):
    global ok, fail
    if got == want: ok += 1; print(f"  ✅ {name}: {got}")
    else: fail += 1; print(f"  ❌ {name}: got {got}, book says {want}")

print("=== 4.1 ===")
# 选05 索引顺序文件 N=10000 最优分组
N = 10000
best = min(((m/2 + N/(2*m), m) for m in range(1, N+1)), key=lambda x: x[0])
chk("4.1选05 最优组数 m", best[1], 100)
chk("4.1选05 最少平均查找次数", int(best[0]), 100)
chk("4.1选05 m=sqrt(N)", int(math.isqrt(N)), 100)

print("=== 4.2 正文算例 ===")
chk("FCB64B/1KB 每块FCB数", 1*K//64, 16)
chk("640个FCB块数", 640//(1*K//64), 40)
chk("640个FCB平均启动", 40//2, 20)
chk("UNIX目录项16B 每块数", 1*K//16, 64)
chk("640项 UNIX 块数", 640//64, 10)
chk("UNIX 平均启动", 10//2, 5)
chk("单级索引 4KB/4B 项数", 4*K//4, 1024)
chk("单级索引最大文件(MB)", 1024*4*K//M, 4)
chk("两级索引最大(GB)", 1024*1024*4*K//G, 4)
# UNIX 13地址项 混合索引 (4KB块,4B地址 -> 1024)
n = 4*K//4
chk("直接10项(KB)", 10*4*K//K, 40)
chk("一次间址(MB)", n*4*K//M, 4)
chk("二次间址(GB)", n*n*4*K//G, 4)
chk("三次间址(TB)", n*n*n*4*K//T, 4)

print("=== 4.2 选择题 ===")
chk("选09 3200FCB/64B/1KB 平均访盘", (3200//(1*K//64))//2, 100)
chk("选10 3200目录项/16B 平均访盘+读inode", (3200//(1*K//16))//2 + 1, 26)
# 选25 记录成组分解 100B记录 512B块
chk("选25 每块记录数", 512//100, 5)
chk("选25 第22记录在第几块", -(-22//5), 5)
chk("选25 总启动次数(5读+1写)", 5+1, 6)
# 选26 1569字节 512B块 链 50,121,75,80,63
blocks = [50,121,75,80,63]
chk("选26 盘块", blocks[1569//512], 80)
# 选28 FAT 簇=2*4KB=8KB, 最大文件512MB
clusters = 512*M//(2*4*K)
chk("选28 簇数", clusters, 2**16)
chk("选28 簇号字节数", 2, 2)
chk("选28 FAT大小(KB)", clusters*2//K, 128)
# 选32 10直接+1一级间接, 4KB块 32位地址
chk("选32 最多磁盘块", 10 + 4*K//4, 1034)
# 选33 两级索引 1KB块 4B盘块号
chk("选33 两级最大(MB)", (1*K//4)**2 * 1*K//M, 64)
# 选34 三级索引 1024B块 4B
chk("选34 三级最大(GB)", (1024//4)**3 * 1024//G, 16)
# 选53 2010真题: 4直接+2一级+1二级, 地址项4B, 块256B
e = 256//4
tot = 4*256 + 2*e*256 + e*e*256
chk("选53 总字节", tot, 1082368)
chk("选53 KB", tot//K, 1057)
# 选59 2015: 10直接+1一级+1二级, 1KB块, 4B指针
p = 1*K//4
d10, l1, l2 = 10*K, p*K, p*p*K
chk("选59 直接覆盖(KB)", d10//K, 10)
chk("选59 一级覆盖(KB)", l1//K, 256)
chk("选59 二级覆盖(MB)", l2//M, 64)
chk("选59 偏移1234 在直接块", 1234 < d10, True)
chk("选59 偏移307400 在二级", d10+l1 < 307400 < d10+l1+l2, True)
# 选60 2017 权限位
chk("选60 位数", 4*5, 20)
# 选62 2017 簇1KB 文件1026B
chk("选62 分配字节", -(-1026//(1*K))*(1*K), 2048)
# 选63 2020 inode号4B
chk("选63 文件数上限", 2**(4*8), 2**32)
